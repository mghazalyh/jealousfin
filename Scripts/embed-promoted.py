#!/usr/bin/env python3
"""Generate deterministic Swift source from reviewed, versioned runtime sources."""
import argparse
import base64
import hashlib
import json
import pathlib
import re

def checked(raw):
    if len(raw)>700*1024:
        raise ValueError("Baseline exceeds supported size")
    m=json.loads(raw)
    if not isinstance(m,dict) or m.get("schemaVersion")!=1:
        raise ValueError("Unknown release schema")
    def ident(v):
        return isinstance(v,str) and re.fullmatch(r"[A-Za-z0-9_-]{1,80}",v) is not None
    if not ident(m.get("revision")):
        raise ValueError("Invalid revision")
    if set(m)-{"schemaVersion","revision","archiveID","deviceID","evidence","sources"}:
        raise ValueError("Unexpected baseline fields")
    for k in ("archiveID","deviceID"):
        if m.get(k) is not None and not ident(m[k]):
            raise ValueError("Invalid "+k)
    if m.get("evidence") is not None and (not isinstance(m["evidence"],str) or len(m["evidence"])>4000):
        raise ValueError("Invalid review evidence")
    sources=m.get("sources")
    if not isinstance(sources,dict) or set(sources)-{"runtime","jellyfinAPI","ui"}:
        raise ValueError("Unexpected source components")
    for k in ("runtime","jellyfinAPI"):
        p=sources.get(k)
        if p is not None:
            if not isinstance(p,dict) or set(p)!={"id","source"} or not ident(p["id"]) or not isinstance(p["source"],str) or not 0<len(p["source"].encode())<=192*1024:
                raise ValueError("Invalid "+k)
    ui=sources.get("ui")
    if ui is not None and (not isinstance(ui,dict) or ui.get("schemaVersion")!=1 or not ident(ui.get("revision"))):
        raise ValueError("Invalid UI schema")
    return m

def generate(raw):
    m=checked(raw)
    # Only the approved revision and executable sources enter the binary.
    # The originating device identity and private review remain in TorrioDB.
    exported={"schemaVersion":m["schemaVersion"],"revision":m["revision"],"sources":m["sources"]}
    data=json.dumps(exported,ensure_ascii=False,sort_keys=True,separators=(",",":")).encode()
    digest=hashlib.sha256(data).hexdigest()
    encoded=base64.b64encode(data).decode()
    chunks=[encoded[i:i+100] for i in range(0,len(encoded),100)]
    # Join short literals at runtime to avoid huge Swift expressions.
    swift="// Generated by Scripts/embed-promoted.py; do not edit.\nimport Foundation\n\nenum BundledPatchBaseline {\n    static let digest = \""+digest+"\"\n    static let encoded = [\n"
    swift+="".join('        "'+c+'",\n' for c in chunks)
    swift+="    ].joined()\n    static func load() throws -> ReleaseBaseline {\n        guard let data=Data(base64Encoded:encoded) else{throw AppError.message(\"Invalid embedded baseline\")}\n        return try JSONCodec.decoder().decode(ReleaseBaseline.self,from:data).checked()\n    }\n}\n"
    return swift,digest

def main():
    p=argparse.ArgumentParser()
    p.add_argument("manifest",type=pathlib.Path)
    p.add_argument("output",type=pathlib.Path)
    args=p.parse_args()
    swift,digest=generate(args.manifest.read_bytes())
    args.output.write_text(swift)
    print("Promoted source digest:",digest)
if __name__=="__main__":
    main()
